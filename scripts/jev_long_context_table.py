"""Jev (D30) by process x long_context x builder class: a small reporting table (post-run; no frozen file changed).

Jev's long-context mode is used only after a `400 max_tokens_exceeded` reply, so it goes with input length and so
with the process (Loan rows are long). This table shows Jev's results within each process x mode, next to the gate
and Haiku's answer-level judge on the same rows. It reuses the reviewed loaders of scripts/main_analysis.py.

usage: python -X utf8 scripts/jev_long_context_table.py <root> <out_dir> [--sets wf_test,ml_test,wf_policy]
"""
import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.dont_write_bytecode = True
import main_analysis as ma  # noqa: E402

JEV = "main_answer_jev|answer|jev-1.14.0"
HAIKU = "main_answer_haiku|answer|claude-haiku-5-5"


def r4(x):
    return None if x is None else round(float(x), 4)


def stats(conf, trust, c, g):
    """Own verdict (rule A: every row here has an answer), the gate on the same rows, and threshold-free AUROC."""
    n = len(c)
    kept = trust.sum()
    out = {"n": int(n), "wrong": int((1 - c).sum()),
           "trusted": int(kept), "trusted_wrong": int((trust * (1 - c)).sum()),
           "own_coverage": r4(kept / n) if n else None, "own_precision": r4((trust * c).sum() / kept) if kept else None,
           "auroc": r4(ma.auroc(conf, c)) if ma.auroc(conf, c) is not None else None,
           "gate_kept": int(g.sum()), "gate_wrong": int((g * (1 - c)).sum()),
           "gate_coverage": r4(g.sum() / n) if n else None, "gate_precision": r4((g * c).sum() / g.sum()) if g.sum() else None,
           "mean_conf_right": r4(conf[c == 1].mean()) if (c == 1).any() else None,
           "mean_conf_wrong": r4(conf[c == 0].mean()) if (c == 0).any() else None}
    return out


def main(root, out_dir, sets):
    sys.path[:0] = [str(root), str(root / "scripts")]
    import main_runner as mr
    import main_summary as ms
    rows, _, _, _, _ = ma.load_rows(root, sets, mr, ms)
    runs = ma.load_judges(root / "runs" / "judges_main_v1", set(sets))
    jev, hk = runs[JEV], runs.get(HAIKU)
    idx = np.array([i for i, r in enumerate(rows) if r["has"] and (r["set"], r["program"], r["question"]) in jev["rows"]])
    jconf, jtrust, jpres = ma.verdict_arrays(rows, idx, jev)
    assert jpres.all()
    hconf, htrust, hpres = ma.verdict_arrays(rows, idx, hk) if hk else (None, None, None)
    c = np.array([float(rows[i]["correct"]) for i in idx])
    g = np.array([float(bool(rows[i]["decisions"]["directed"]["permit"])) for i in idx])
    lc = [bool(jev["rows"][(rows[i]["set"], rows[i]["program"], rows[i]["question"])].get("long_context")) for i in idx]
    grp = defaultdict(list)
    for pos, i in enumerate(idx):
        r = rows[i]
        part = "main" if r["set"] in ("wf_test", "ml_test") else r["set"]
        for cls in (r["class"], "all"):
            grp[(part, r["process"], cls, "long" if lc[pos] else "default")].append(pos)
            grp[(part, r["process"], cls, "both")].append(pos)
    res = {"what": __doc__.strip().splitlines()[0], "sets": sets, "rows_with_jev": int(len(idx)),
           "jev_rows_total": len(jev["rows"]), "groups": {}}
    for key in sorted(grp):
        p = np.array(grp[key])
        if key[2] == "all":                 # Claude-built and Ollama-built are never pooled: counts only (review fix)
            res["groups"]["|".join(key)] = {"counts_only": {"n": int(len(p)), "wrong": int((1 - c[p]).sum())}}
            continue
        e = {"jev": stats(jconf[p], jtrust[p], c[p], g[p])}
        if hk is not None and hpres[p].all():
            e["haiku_answer"] = stats(hconf[p], htrust[p], c[p], g[p])
        res["groups"]["|".join(key)] = e
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "jev_long_context.json").write_text(json.dumps(res, indent=1), encoding="utf-8")
    (out_dir / "jev_long_context.md").write_text(render(res), encoding="utf-8")
    print(f"rows with a Jev judgment {len(idx)} of {len(jev['rows'])}; wrote {out_dir}")


def f3(x):
    return "-" if x is None else f"{x:.3f}"


def render(res):
    out = ["# Jev (D30) by process x long-context mode", "",
           f"Generated by scripts/jev_long_context_table.py from the scored rows and Jev's judgment rows; {res['rows_with_jev']} rows (sets {', '.join(res['sets'])}).",
           "'long' = the default request got `400 max_tokens_exceeded` and was resent once with the long-context header (rule fixed before any call, D30).",
           "Jev's own verdict is TRUST at p >= 0.5, so its coverage and precision depend on that threshold; AUROC needs none. "
           "The gate and Haiku's answer-level judge are shown on the same rows. Claude-built and Ollama-built programs are never pooled; 'all' rows give counts only.",
           "'long' against 'default' is not a controlled comparison: the mode is set by input length, which goes with the process and the program. "
           "Many cells rest on few wrong answers (IT: 1-3 for Claude-built programs; Manufacturing: none), so their AUROC and precision say little; read them with the counts.", "",
           "| part | process | built by | mode | rows | wrong answers | Jev own cov/prec (wrong Trusted) | Jev AUROC | Jev mean conf right / wrong | Haiku answer own cov/prec (wrong Trusted) | Haiku AUROC | gate cov/prec (wrong Trusted) |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for k, e in res["groups"].items():
        part, proc, cls, mode = k.split("|")
        if cls == "all":
            j = e["counts_only"]
            out.append(f"| {part} | {proc} | all | {mode} | {j['n']} | {j['wrong']} | - | - | - | - | - | - |")
            continue
        j, h = e["jev"], e.get("haiku_answer")
        hc = "-" if not h else f"{f3(h['own_coverage'])}/{f3(h['own_precision'])} ({h['trusted_wrong']})"
        ha = "-" if not h else f3(h["auroc"])
        out.append(f"| {part} | {proc} | {cls} | {mode} | {j['n']} | {j['wrong']} | {f3(j['own_coverage'])}/{f3(j['own_precision'])} ({j['trusted_wrong']}) | "
                   f"{f3(j['auroc'])} | {f3(j['mean_conf_right'])} / {f3(j['mean_conf_wrong'])} | {hc} | {ha} | "
                   f"{f3(j['gate_coverage'])}/{f3(j['gate_precision'])} ({j['gate_wrong']}) |")
    out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("out_dir")
    ap.add_argument("--sets", default="wf_test,ml_test,wf_policy")
    a = ap.parse_args()
    main(Path(a.root).resolve(), Path(a.out_dir), a.sets.split(","))
